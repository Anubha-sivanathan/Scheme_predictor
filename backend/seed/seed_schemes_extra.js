if (schemes.length !== 50) {
  throw new Error("Expected 50 schemes, found " + schemes.length);
}
const names = new Set(schemes.map((s) => s.name));
if (names.size !== schemes.length) {
  throw new Error("Duplicate scheme names in seed");
}
schemes.forEach((s) => {
  if (!/^https:\/\//.test(s.applicationLink)) throw new Error("Non-https link for " + s.name);
});

schemes.forEach((s) => {
  const { createdAt, ...rest } = s;
  db.schemes.updateOne(
    { name: s.name },
    { $set: rest, $setOnInsert: { createdAt } },
    { upsert: true }
  );
});

print("Upserted " + schemes.length + " schemes. Collection now has " + db.schemes.countDocuments({}) + " schemes.");
