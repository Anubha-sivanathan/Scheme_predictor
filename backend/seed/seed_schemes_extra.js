// DATA INTEGRITY NOTES
//  * applicationLink is the scheme's own official portal (or the owning department's portal). Every link
//    here returned HTTP 200 on 2026-10-27 (see linkVerifiedOn); that proves the site is reachable, NOT that
//    the page content still matches the text below.
//  * Descriptions/benefits are short plain-language summaries. eligibilityCriteria contains only criteria
//    that are stable and well-known; anything uncertain is deliberately left out so the rule engine reports
//    it as unknown rather than guessing. An administrator should re-check every entry against its official
//    page before go-live. Scheme rules change; the official text always prevails.
//  * No deadlines are set: none were verified, and inventing one would be worse than showing none.
//  * Text is kept in English as the official wording. It is not machine-translated.

db = db.getSiblingDB("scheme_predictor");

const now = new Date();
const VERIFIED_ON = "2026-10-27";

function scheme(name, department, category, description, benefits, eligibilityCriteria, requiredDocuments, applicationProcess, applicationLink) {
  const host = new URL(applicationLink).host;
  return {
    name, department, category, description, benefits, eligibilityCriteria, requiredDocuments,
    applicationProcess, applicationLink,
    dataSource: "Official portal: " + host,
    linkVerifiedOn: VERIFIED_ON,
    deadline: null,
    status: "ACTIVE",
    createdAt: now,
    updatedAt: now,
  };
}

